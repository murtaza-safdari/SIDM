#!/usr/bin/env python3
"""make_dag_v2.py -- the DAGMan DAGs of the v2 production (chain_job_v2.sh): one sub-DAG per era column / grid, one
node per chunk, and one outer DAG that runs them two at a time.

    make_dag_v2.py ERA column  OUTDIR    # the 36 reduced_points.txt samples x 100k events (v1 chunking:
                                         #   j000-j039 at 500 events + j040-j119 at 1000 events = 120 chunks)
    make_dag_v2.py ERA grid    OUTDIR    # the 180 points_all.txt samples x 2000 events (j000-j003 at 500), as v1;
                                         #   the 36 column samples' j000-j003 are the column's files, so those
                                         #   nodes skip in seconds (output already on EOS) or redo a lost chunk
    make_dag_v2.py outer       TOPDIR    # TOPDIR/run3v2.dag: SUBDAG EXTERNAL per TOPDIR/<era>_<kind>/<era>_<kind>.dag

A sub-DAG dir gets <era>_<kind>.dag (JOB/VARS/RETRY 3 per node, its own CONFIG and NODE_STATUS_FILE),
<era>_<kind>.config (DAGMAN_MAX_JOBS_IDLE = 500, DAGMAN_MAX_JOBS_SUBMITTED = 1500), prod_v2.sub with the era's
request_memory / request_disk filled in, a copy of chain_job_v2.sh, and logs/ cksum/ faillog/.
The outer DAG (own CONFIG: DAGMAN_MAX_JOBS_SUBMITTED = 2, so two sub-DAGs run at a time; PRIORITY sets the order:
the five columns, then the five grids, 2024 first) is submitted once:
    cd TOPDIR && _CONDOR_DAGMAN_INSERT_SUB_FILE=$PWD/dagman_insert.sub condor_submit_dag -notification never run3v2.dag
The LPC schedd rejects any job without a DesiredOS or an Apptainer image. condor_submit on a login node adds the
client's DesiredOS = "EL9", but the outer DAGMan submits the sub-DAGMan jobs on the schedd without it ("Please
specify a valid DesiredOS"). dagman_insert.sub (+DesiredOS = "EL9") reaches those jobs through
DAGMAN_INSERT_SUB_FILE: set in the environment at submit time, passed on by DAGMan's getenv = _CONDOR_*, read by
the recursive condor_submit_dag -no_submit that writes each sub-DAG's .condor.sub. (condor_submit_dag does not read
that knob from a DAG's CONFIG file.)
A sub-DAG that was run before starts from its rescue DAG (DAGMan's default), and chain_job_v2.sh skips any chunk whose
output is already on EOS.
"""
import os, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ERAS = ["2022", "2022EE", "2023", "2023BPix", "2024"]
ORDER = ["2024", "2022", "2022EE", "2023", "2023BPix"]          # within columns, then within grids
MEMORY = {"2024": "9500MB"}                                    # 1.3 x the 7.0 GB PREMIX peak of the 2024 test job
MEMORY_DEFAULT = "7500MB"                                      # 1.3 x the 5.0-5.6 GB peaks of the other eras
DISK = "4GB"                                                   # 1.5 x the ~2.5 GB footprint of a 1000-event chunk
STATUS_PERIOD = 600                                            # s between NODE_STATUS_FILE rewrites


def points(fname):
    out = []
    for line in open(os.path.join(HERE, fname)):
        p = line.strip().split("_")
        if p and p[0]:
            out.append((p[1][:-3], p[2][:-3].replace("p", "."), p[0], p[3][:-2].replace("p", ".")))  # MBs MDp CHAN CTAU
    return out


def chunks(kind):
    if kind == "column":
        return [(f"j{j:03d}", 500) for j in range(40)] + [(f"j{j:03d}", 1000) for j in range(40, 120)]
    return [(f"j{j:03d}", 500) for j in range(4)]


def sub_dag(era, kind, outdir):
    col = points("reduced_points.txt")
    pts = col if kind == "column" else points("points_all.txt")
    name = f"{era}_{kind}"
    lines = [f"# v2 {era} {kind}: {len(pts)} samples, generated by make_dag_v2.py",
             f"CONFIG {name}.config", f"NODE_STATUS_FILE {name}.status {STATUS_PERIOD}"]
    n = 0
    for mbs, mdp, chan, ctau in pts:
        for jidx, nev in chunks(kind):
            node = f"{chan}_{mbs}_{mdp.replace('.', 'p')}_{ctau.replace('.', 'p')}_{jidx}"
            ck = f"SIDM_BsTo2DpTo{chan}_MBs-{mbs}_MDp-{mdp.replace('.', 'p')}_ctau-{ctau.replace('.', 'p')}_{era}_{jidx}.cksum"
            lines += [f"JOB {node} prod_v2.sub",
                      f'VARS {node} MBs="{mbs}" MDp="{mdp}" CHAN="{chan}" CTAU="{ctau}" ERA="{era}" NEV="{nev}" JOBIDX="{jidx}" CKSUM="{ck}" FAILLOG="{ck[:-6]}.faillog.gz" KIND="{kind}"',
                      f"RETRY {node} 3"]
            n += 1
    for sub in ("", "logs", "cksum", "faillog"):   # condor creates neither the log nor the remap directories
        os.makedirs(os.path.join(outdir, sub), exist_ok=True)
    open(os.path.join(outdir, f"{name}.dag"), "w").write("\n".join(lines) + "\n")
    open(os.path.join(outdir, f"{name}.config"), "w").write(
        "# throttles of one v2 sub-DAG (batch etiquette: idle depth <= 500 per DAG, two DAGs at a time)\n"
        "DAGMAN_MAX_JOBS_IDLE = 500\nDAGMAN_MAX_JOBS_SUBMITTED = 1500\n")
    sub = open(os.path.join(HERE, "prod_v2.sub")).read()
    sub = sub.replace("@MEMORY@", MEMORY.get(era, MEMORY_DEFAULT)).replace("@DISK@", DISK)
    assert "@MEMORY@" not in sub and "@DISK@" not in sub, "unfilled placeholder in prod_v2.sub"
    open(os.path.join(outdir, "prod_v2.sub"), "w").write(sub)
    shutil.copy2(os.path.join(HERE, "chain_job_v2.sh"), os.path.join(outdir, "chain_job_v2.sh"))
    print(f"wrote {outdir}/{name}.dag: {n} nodes ({len(pts)} samples), memory {MEMORY.get(era, MEMORY_DEFAULT)}")


def outer(topdir):
    order = [(e, "column") for e in ORDER] + [(e, "grid") for e in ORDER]
    lines = ["# v2 SIDM Run 3 campaign: ten sub-DAGs, two at a time (CONFIG), highest PRIORITY first; no edges.",
             "CONFIG run3v2.config", f"NODE_STATUS_FILE run3v2.status {STATUS_PERIOD}"]
    for i, (e, k) in enumerate(order):
        name = f"{e}_{k}"
        assert os.path.exists(os.path.join(topdir, name, f"{name}.dag")), f"missing sub-DAG {name}"
        lines += [f"SUBDAG EXTERNAL {name} {name}.dag DIR {name}", f"PRIORITY {name} {len(order) - i}"]
    open(os.path.join(topdir, "run3v2.dag"), "w").write("\n".join(lines) + "\n")
    open(os.path.join(topdir, "dagman_insert.sub"), "w").write(
        "# inserted into every sub-DAGMan job: the LPC schedd requires a DesiredOS (or an Apptainer image) on every job\n"
        '+DesiredOS = "EL9"\n')
    open(os.path.join(topdir, "run3v2.config"), "w").write(
        "# outer DAG: two sub-DAGs (DAGMan jobs) at a time; the next starts when one finishes\n"
        "DAGMAN_MAX_JOBS_SUBMITTED = 2\n")
    print(f"wrote {topdir}/run3v2.dag: {len(order)} sub-DAGs")


def main():
    if sys.argv[1] == "outer":
        return outer(sys.argv[2])
    era, kind, outdir = sys.argv[1:4]
    assert era in ERAS and kind in ("column", "grid"), (era, kind)
    sub_dag(era, kind, outdir)


if __name__ == "__main__":
    main()
